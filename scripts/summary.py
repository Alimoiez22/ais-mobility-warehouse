"""Collect every headline number into results/summary.md (no database needed).

Usage: uv run python scripts/summary.py

The README points to this file, so every number a reader sees is regenerated by
`make all` from the result files, never typed by hand.
"""

from __future__ import annotations

import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
R = ROOT / "results"


def read(path: Path) -> list[dict[str, str]]:
    if not path.exists():
        return []
    with path.open(encoding="utf-8") as f:
        return list(csv.DictReader(f))


def n(v: str) -> str:
    try:
        f = float(v)
    except (TypeError, ValueError):
        return v or ""
    return f"{int(f):,}" if f.is_integer() else f"{f:,.2f}"


def table(headers: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    lines += ["| " + " | ".join(str(c).replace("|", "\\|") for c in r) + " |" for r in rows]
    return "\n".join(lines)


def main() -> int:
    md = ["# Results summary", "",
          "Generated by `scripts/summary.py` from the files in `results/`. Do not edit by hand.", ""]

    load = read(R / "staging_rowcount.csv")
    if load:
        md += ["## Load", "", table(["Source file", "Rows loaded", "Staging table size"],
                                    [[load[0]["source_file"], n(load[0]["rows_loaded"]), load[0]["table_size"]]]), ""]

    clean = read(R / "cleaning.csv")
    if clean:
        md += ["## RQ1: cleaning rules (in the order they run)", "",
               table(["Step", "Rule", "Rows before", "Removed", "Rows after", "% of raw"],
                     [[c["step"], c["rule"], n(c["rows_before"]), n(c["rows_removed"]), n(c["rows_after"]),
                       c["pct_of_raw"]] for c in clean]),
               "", "![Cleaning](../docs/figures/cleaning.png)", ""]

    trips = read(R / "trips_compare.csv")
    if trips:
        md += ["## Trips: comparing gap values", "",
               table(["Gap (min)", "Trips", "Ships", "Single-report pieces", "Median points",
                      "Median duration (min)", "Median length (km)", "Trips > 50 kn max speed"],
                     [[t["gap_minutes"], n(t["trips"]), n(t["ships"]), n(t["single_report_segments"]),
                       n(t["median_points"]), t["median_duration_min"], t["median_length_km"],
                       n(t["trips_max_speed_over_50kn"])] for t in trips]), ""]

    star = read(R / "star_counts.csv")
    if star:
        md += ["## Warehouse tables", "", table(["Table", "Rows"], [[s["table_name"], n(s["row_count"])] for s in star]), ""]

    olap = read(R / "olap_runtimes.csv")
    if olap:
        md += ["## RQ2: OLAP queries", "",
               table(["Query", "Business question", "Result rows", "Execution (ms)"],
                     [[o["query"], o["question"], o["result_rows"], n(o["execution_ms"])] for o in olap]),
               "", "Full results: `results/olap/`.", ""]

    bench = read(R / "bench" / "summary.csv")
    idx = read(R / "bench" / "indexes.csv")
    if bench:
        md += ["## RQ3: spatial index benchmark (warm cache, 5 runs)", "",
               table(["Query", "Index", "Median (ms)", "IQR (ms)", "Speed-up vs none"],
                     [[b["query"], b["config"], n(b["median_ms"]), n(b["iqr_ms"]), b["speedup_vs_none"]] for b in bench]),
               ""]
        if idx:
            md += [table(["Index", "Build time (s)", "Size"], [[i["config"], i["build_seconds"], i["size"]] for i in idx]), ""]
        md += ["![Benchmark](../docs/figures/benchmark.png)", "",
               "Hardware and settings: `results/bench/environment.txt`. Plans: `results/bench/plans/`.", ""]

    (R / "summary.md").write_text("\n".join(md), encoding="utf-8", newline="\n")
    print("Wrote results/summary.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
